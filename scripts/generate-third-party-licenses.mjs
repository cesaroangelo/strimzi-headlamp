/**
 * Regenerates THIRD-PARTY-LICENSES.md.
 *
 * The build bundles its runtime dependencies into dist/main.js, so their
 * licence notices must ship with the plugin. Headlamp provides React, MUI and
 * the other modules the build marks as external, so those are left out.
 *
 * Run `npm run licenses` after changing any runtime dependency.
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

// Provided by Headlamp at runtime, so never part of the bundle.
const EXTERNAL = new Set(['react', 'react-dom', 'scheduler', 'loose-envify', 'js-tokens']);

const LICENSE_FILES = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENCE', 'license.md'];

function collect(node, found = new Map()) {
  for (const [name, info] of Object.entries(node.dependencies ?? {})) {
    if (!found.has(name) && !name.startsWith('@types/') && !EXTERNAL.has(name)) {
      found.set(name, info.version);
    }
    collect(info, found);
  }
  return found;
}

function licenseText(name) {
  for (const file of LICENSE_FILES) {
    const full = path.join('node_modules', name, file);
    if (fs.existsSync(full)) return fs.readFileSync(full, 'utf8').trim();
  }
  return null;
}

function copyrightLine(text) {
  return text?.split('\n').find(line => /copyright/i.test(line))?.trim() ?? 'See the licence text below.';
}

const tree = JSON.parse(
  execFileSync('npm', ['ls', '--omit=dev', '--all', '--json'], { encoding: 'utf8', maxBuffer: 32e6 })
);

const groups = new Map();
for (const [name, version] of [...collect(tree)].sort()) {
  const pkg = JSON.parse(fs.readFileSync(path.join('node_modules', name, 'package.json'), 'utf8'));
  const id = pkg.license ?? 'UNKNOWN';
  const text = licenseText(name);
  if (!groups.has(id)) groups.set(id, { packages: [], text });
  groups.get(id).packages.push({ name, version, copyright: copyrightLine(text) });
  if (!groups.get(id).text && text) groups.get(id).text = text;
}

let out = `# Third-party licences

\`dist/main.js\` bundles the packages below. Their licences are reproduced here
as those licences require. Modules that Headlamp provides at runtime, such as
React and MUI, are not bundled and are not listed.

Generated by \`npm run licenses\`. Do not edit by hand.
`;

for (const [id, group] of [...groups].sort()) {
  out += `\n## ${id}\n\n`;
  for (const p of group.packages) out += `- **${p.name}** ${p.version} — ${p.copyright}\n`;
  out += `\n<details>\n<summary>Licence text</summary>\n\n\`\`\`\n${group.text ?? 'No licence file shipped with the package.'}\n\`\`\`\n\n</details>\n`;
}

fs.writeFileSync('THIRD-PARTY-LICENSES.md', out);
console.log(`Wrote THIRD-PARTY-LICENSES.md (${[...groups.values()].reduce((n, g) => n + g.packages.length, 0)} packages)`);
